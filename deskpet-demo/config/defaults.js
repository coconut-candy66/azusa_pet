// ============================================================
// config/defaults.js —— 2D 版全部参数的「默认值」与「说明书」
//
// 和 3D 版一样，这个文件有两个作用：
//   1. 代码里所有写死的数字，全部搬到这里，成为唯一的真相来源
//   2. 用户配置漏了某一项、或者干脆写坏了，就退回这里的值
//
// ★ 你平时不需要改这个文件。
//   要调参数请改 desktop/config.js（那里有完整的一份带注释的副本）。
//
// ------------------------------------------------------------
// 2D 版和 3D 版的区别，一句话：
//   3D 是「一台相机拍一个立体的东西」，所以要管相机、灯光、材质；
//   2D 是「一张贴图贴在屏幕上」，没有相机也没有灯光 ——
//   但换来了一件 3D 做不到的事：**换贴图就能换表情**。
//   所以下面没有 camera / lights，多出来的是 sprite（立绘）和 hit（命中判定）。
//
// 坐标系约定（2D 版）：
//   - 舞台是窗口本身，坐标单位是 CSS 像素，原点在左上角
//   - 立绘的锚点在【脚底中线】—— 所以它做压扁动画时脚是不动的，
//     这符合直觉（人蹲下去脚不会离地）
//   - 所有「位置类」参数写成 0~1 的比例，不写绝对像素。
//     这样你改窗口大小，立绘跟着一起缩放，不用重调。
// ============================================================

