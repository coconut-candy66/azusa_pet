      //   happy / surprise 只是预留，程序不会拿它们换图 ——
      //   AI 重画的「同角色不同表情」是另一张整身立绘，直接换会闪。
      idle: 'idle.png',                 // 平常 —— ★ 真正用到的只有这一张
