  //     改窗口只会多出一圈透明的留白，人一点儿没变大。
  //
  //   ★ heightRatio 和「气泡放哪儿」是联动算出来的：
  //     头顶到窗口顶要留一条带子放 HUD 和气泡，
  //     0.60 时头顶在窗口高度的 40% 处 = 上面留 104px，够两层。
