    //   ★ 为什么要用 root + outfits 两个参数？
    //     以前只有一个 dir，想换装就得改 dir 然后等自动重启。
    //     现在把「所有套」都列出来，点一下就在它们之间随机跳，
    //     不用重启、不用改配置。
    //
    //   想固定看某一套？把 outfitSwitch.enabled 改成 false，
    //   再看 dir 指向哪儿（dir 仍然是要用的那一套）。
