  //     ① 放进 deskpet-demo/assets/sprites/
  //     ② 把下面 enabled 改成 true
  //     ③ 用 tools/make-sprite.py 烘焙一张命中遮罩 mask.json
  //   代码一行都不用动。
  //
  //   ★ 现在只用 idle 这一张：表情和眨眼都不做了，只展示立绘 + 点击换装。
